# ==================== GAMEPLAY ====================
REFERENCE_GRID_SIZE = 32
BASE_MOVE_INTERVAL = 0.15  # seconds

def get_player_move_interval(grid_size=None):
    if grid_size is None:
        grid_size = GRID_SIZE
    return BASE_MOVE_INTERVAL * (REFERENCE_GRID_SIZE / float(grid_size))

def get_enemy_move_interval(grid_size=None):
    return get_player_move_interval(grid_size) * 1.4  # 40% slower (original Java game behavior)

# Expose the base functions at module level for easier access

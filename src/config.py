# ==================== GRID & DISPLAY ====================
GRID_DENSITY = "large"
SCREEN_SIZE = 600

def get_default_grid_size(screen_size):
    if screen_size == 600:
        if GRID_DENSITY == "small":
            return 15
        if GRID_DENSITY == "large":
            return 25
        return 20  # medium for 600x600
    elif screen_size == 800:
        if GRID_DENSITY == "small":
            return 16
        if GRID_DENSITY == "large":
            return 32
        return 25  # medium for 800x800
    elif screen_size == 1000:
        if GRID_DENSITY == "small":
            return 20
        if GRID_DENSITY == "large":
            return 40
        return 40  # medium for 1000x1000
    else:
        return 25  # fallback


def validate():
    if SCREEN_SIZE % GRID_SIZE != 0:
        raise ValueError(f"SCREEN_SIZE ({SCREEN_SIZE}) must be divisible by GRID_SIZE ({GRID_SIZE})")
    if not 10 <= GRID_SIZE <= 100:
        raise ValueError(f"GRID_SIZE must be between 10 and 100, got: {GRID_SIZE}")
    if BASE_MOVE_INTERVAL <= 0:
        raise ValueError(f"BASE_MOVE_INTERVAL must be positive, got: {BASE_MOVE_INTERVAL}")
    if get_player_move_interval() <= 0:
        raise ValueError(f"Calculated player move interval must be positive, got: {get_player_move_interval()}")

